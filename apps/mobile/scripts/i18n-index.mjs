/**
 * Regenerates src/i18n/locales/<lang>/index.ts and src/i18n/resources.ts from the namespace files
 * that exist. Run after adding a language or namespace:  node scripts/i18n-index.mjs
 */
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const LOCALES = resolve(import.meta.dirname, '../src/i18n/locales');
const LANGS = ['en', 'pcm', 'yo', 'ig', 'ha', 'fr', 'ar', 'sw', 'pt', 'es'];
const namespaces = readdirSync(resolve(LOCALES, 'en'))
  .filter((f) => f.endsWith('.ts') && f !== 'index.ts')
  .map((f) => f.replace(/\.ts$/, ''))
  .sort();

const id = (s) => s.replace(/-(\w)/g, (_, c) => c.toUpperCase());

for (const lang of LANGS.filter((l) => l !== 'en')) {
  const dir = resolve(LOCALES, lang);
  const have = existsSync(dir) ? namespaces.filter((ns) => existsSync(resolve(dir, `${ns}.ts`))) : [];
  if (!have.length) continue;
  const src = [
    "import type { Translation } from '../../types';",
    "import type en from '../en';",
    '',
    ...have.map((ns) => `import ${id(ns)} from './${ns}';`),
    '',
    `/** Generated by scripts/i18n-index.mjs. Missing namespaces fall back to English. */`,
    `const ${id(lang)}: Translation<typeof en> = { ${have.map(id).join(', ')} };`,
    '',
    `export default ${id(lang)};`,
    '',
  ].join('\n');
  writeFileSync(resolve(dir, 'index.ts'), src);
  console.log(`${lang}: ${have.length}/${namespaces.length} namespaces`);
}

const present = LANGS.filter((l) => existsSync(resolve(LOCALES, l, 'index.ts')));
writeFileSync(
  resolve(LOCALES, '../resources.ts'),
  [
    "import type { LanguageId } from './languages';",
    ...present.map((l) => `import ${id(l)} from './locales/${l}';`),
    "import type { Translation } from './types';",
    '',
    '/** All bundled translations. Generated by scripts/i18n-index.mjs. */',
    'export const resources: Record<LanguageId, Translation<typeof en>> = {',
    ...LANGS.map((l) => (present.includes(l) ? `  ${l},` : `  ${l}: {},`)),
    '};',
    '',
  ].join('\n'),
);
